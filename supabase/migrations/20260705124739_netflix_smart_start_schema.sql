/*
# Netflix Smart Start Schema

## Overview
Creates tables for the Netflix Smart Start viewing companion prototype.
This is a single-tenant app (no auth), so all tables use anon + authenticated policies.

## New Tables

### watch_progress
Tracks what the user has watched for each show.
- id: primary key
- show_id: references the static show catalog (stored as text since catalog is client-side)
- season_num: current season number
- episode_num: current episode number within the season
- last_watched_at: timestamp of last viewing session
- total_minutes_watched: cumulative watch time in minutes
- status: 'watching', 'completed', 'dropped', 'paused'

### watch_plans
Stores personalized watch plans generated by Smart Start.
- id: primary key
- show_id: the show this plan is for
- mood: the mood that triggered this plan
- available_minutes: time budget the user had when the plan was created
- plan_episodes: JSONB array of planned episodes with schedule
- notes: optional user notes about the plan
- created_at: when the plan was created
- active: whether this is the user's current active plan for the show

### mood_sessions
Stores mood + time sessions so Smart Start remembers recent preferences.
- id: primary key
- mood: selected mood
- available_minutes: time budget selected
- show_ids_recommended: JSONB array of show IDs that were recommended
- created_at: timestamp

## Security
RLS enabled on all tables. anon + authenticated policies since no login screen.
*/

-- Watch Progress Table
CREATE TABLE IF NOT EXISTS watch_progress (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  show_id text NOT NULL,
  season_num integer NOT NULL DEFAULT 1,
  episode_num integer NOT NULL DEFAULT 1,
  last_watched_at timestamptz DEFAULT now(),
  total_minutes_watched integer NOT NULL DEFAULT 0,
  status text NOT NULL DEFAULT 'watching' CHECK (status IN ('watching', 'completed', 'dropped', 'paused')),
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

ALTER TABLE watch_progress ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "anon_select_watch_progress" ON watch_progress;
CREATE POLICY "anon_select_watch_progress" ON watch_progress FOR SELECT
  TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "anon_insert_watch_progress" ON watch_progress;
CREATE POLICY "anon_insert_watch_progress" ON watch_progress FOR INSERT
  TO anon, authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "anon_update_watch_progress" ON watch_progress;
CREATE POLICY "anon_update_watch_progress" ON watch_progress FOR UPDATE
  TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "anon_delete_watch_progress" ON watch_progress;
CREATE POLICY "anon_delete_watch_progress" ON watch_progress FOR DELETE
  TO anon, authenticated USING (true);

-- Watch Plans Table
